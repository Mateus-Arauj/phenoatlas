"""
Comparison tests: phenoatlas (Python) vs phenofit (R) reference outputs.

Reference CSVs are generated by:
    Rscript validation/r/generate_references.R

All comparisons use atol=1e-4 unless tighter tolerances are achievable.
"""
from __future__ import annotations

import os

import numpy as np
import pandas as pd
import pytest

# Skip entire module if reference data is missing (R not available)
REF_DIR = os.path.join(os.path.dirname(__file__), "..", "validation", "reference_data")
_REFS_PRESENT = os.path.isdir(REF_DIR) and os.path.isfile(
    os.path.join(REF_DIR, "curves.csv")
)

pytestmark = pytest.mark.skipif(
    not _REFS_PRESENT, reason="Reference data missing — run validation/r/generate_references.R"
)

from phenoatlas.fitting.curves import (
    doubleLog_AG,
    doubleLog_Beck,
    doubleLog_Elmore,
    doubleLog_Gu,
    doubleLog_Zhang,
)
from phenoatlas.fitting.curvefit import curvefit
from phenoatlas.smoothing.whittaker import smooth_whit


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load(name: str) -> pd.DataFrame:
    return pd.read_csv(os.path.join(REF_DIR, name))


def input_data() -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    df = load("input_data.csv")
    return df["t"].to_numpy(), df["y_noisy"].to_numpy(), df["w"].to_numpy()


# ---------------------------------------------------------------------------
# 1. Curve functions
# ---------------------------------------------------------------------------

class TestCurveFunctions:
    """Exact match of doubleLog_* against R reference at known parameters."""

    def setup_method(self):
        self.curves_ref = load("curves.csv")
        self.t = self.curves_ref["t"].to_numpy()
        params = load("curve_params.csv").set_index("method")
        # Strip NaN trailing columns and convert to list
        self.params = {
            m: row.dropna().values.tolist()
            for m, row in params.iterrows()
        }

    def _cmp(self, method: str, fn, atol: float = 1e-6):
        p = np.array(self.params[method])
        y_py = fn(self.t, p)
        y_r  = self.curves_ref[method].to_numpy()
        np.testing.assert_allclose(
            y_py, y_r, atol=atol,
            err_msg=f"{method} curve mismatch vs R reference"
        )

    def test_Beck(self):    self._cmp("Beck",   doubleLog_Beck)
    def test_Elmore(self):  self._cmp("Elmore", doubleLog_Elmore)
    def test_Zhang(self):   self._cmp("Zhang",  doubleLog_Zhang)
    def test_AG(self):      self._cmp("AG",     doubleLog_AG)
    def test_Gu(self):      self._cmp("Gu",     doubleLog_Gu)


# ---------------------------------------------------------------------------
# 2. Whittaker smoother
# ---------------------------------------------------------------------------

class TestWhittaker:
    """Compare smooth_whit output against R's smooth_wWHIT (fixed lambda)."""

    def setup_method(self):
        t, y, w = input_data()
        self.t, self.y, self.w = t, y, w

    def _cmp(self, lam: int, atol: float = 1e-4, skip_boundary: bool = False):
        ref = load(f"whittaker_lam{lam}.csv")
        z_r = ref["z"].to_numpy()
        z_py = smooth_whit(self.y, w=self.w, lam=lam, iters=1)
        # With very high lambda the two sparse solvers can differ at
        # boundary points (R uses a slightly different endpoint treatment).
        # Compare interior points only when skip_boundary=True.
        sl = slice(2, -2) if skip_boundary else slice(None)
        np.testing.assert_allclose(
            z_py[sl], z_r[sl], atol=atol,
            err_msg=f"Whittaker lam={lam} mismatch vs R reference"
        )

    def test_lam10(self):   self._cmp(10)
    def test_lam100(self):  self._cmp(100)
    def test_lam1000(self): self._cmp(1000, skip_boundary=True)


# ---------------------------------------------------------------------------
# 3. curvefit GOF statistics
# ---------------------------------------------------------------------------

class TestCurvefitGOF:
    """
    Compare RMSE and R2 from curvefit() against R's get_GOF().

    Optimizer parameters may differ between R and Python, while the fitted
    quality should remain numerically equivalent.
    """

    # Small optimizer-specific differences are allowed.
    ATOL_RMSE = 1e-3
    ATOL_R2   = 1e-3

    def setup_method(self):
        t, y, w = input_data()
        self.t, self.y, self.w = t, y, w
        self.gof_ref = load("curvefit_gof.csv").set_index("meth")

    def _cmp_method(self, method: str):
        result = curvefit(self.y, self.t, methods=[method], w=self.w)
        gof_py = result.get_gof(method)
        rmse_r = float(self.gof_ref.loc[method, "RMSE"])
        r2_r   = float(self.gof_ref.loc[method, "R2"])

        assert abs(gof_py["RMSE"] - rmse_r) < self.ATOL_RMSE, (
            f"{method} RMSE: Python={gof_py['RMSE']:.5f}, R={rmse_r:.5f}"
        )
        assert abs(gof_py["R2"] - r2_r) < self.ATOL_R2, (
            f"{method} R2: Python={gof_py['R2']:.5f}, R={r2_r:.5f}"
        )

    def test_Beck(self):   self._cmp_method("Beck")
    def test_Elmore(self): self._cmp_method("Elmore")
    def test_Zhang(self):  self._cmp_method("Zhang")
    def test_AG(self):     self._cmp_method("AG")
    def test_Gu(self):     self._cmp_method("Gu")
    def test_Klos(self):   self._cmp_method("Klos")


