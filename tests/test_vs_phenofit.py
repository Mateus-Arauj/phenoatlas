# 4. Phenology dates
# ---------------------------------------------------------------------------

class TestPhenology:
    """
    Compare all phenology dates against the R reference.
    """

    DOY_ATOL = 0.1

    def setup_method(self):
        from phenoatlas.phenology.extraction import get_pheno
        t, y, w = input_data()
        result = curvefit(y, t, methods=["Beck"], w=w)
        pheno_df = get_pheno(result)
        # get_pheno returns a tidy DataFrame with phenophase columns
        # e.g. columns: season, fit_method, TRS2.SOS, TRS2.EOS, ...
        self.row = pheno_df.iloc[0]

    def test_TRS2_SOS(self):
        ref = load("pheno_trs.csv").set_index("method")
        sos_r = float(ref.loc["TRS2", "SOS"])
        sos_py = float(self.row["TRS2.SOS"])
        assert abs(sos_py - sos_r) <= self.DOY_ATOL, (
            f"TRS2.SOS: Python={sos_py:.1f}, R={sos_r:.1f}"
        )

    def test_TRS2_EOS(self):
        ref = load("pheno_trs.csv").set_index("method")
        eos_r = float(ref.loc["TRS2", "EOS"])
        eos_py = float(self.row["TRS2.EOS"])
        assert abs(eos_py - eos_r) <= self.DOY_ATOL, (
            f"TRS2.EOS: Python={eos_py:.1f}, R={eos_r:.1f}"
        )

    def test_TRS5_SOS(self):
        ref = load("pheno_trs.csv").set_index("method")
        sos_r = float(ref.loc["TRS5", "SOS"])
        sos_py = float(self.row["TRS5.SOS"])
        assert abs(sos_py - sos_r) <= self.DOY_ATOL

    def test_TRS5_EOS(self):
        ref = load("pheno_trs.csv").set_index("method")
        eos_r = float(ref.loc["TRS5", "EOS"])
        eos_py = float(self.row["TRS5.EOS"])
        assert abs(eos_py - eos_r) <= self.DOY_ATOL

    def test_DER_SOS(self):
        ref = load("pheno_der.csv")
        sos_r = float(ref["DER.SOS"].iloc[0])
        sos_py = float(self.row["DER.SOS"])
        assert abs(sos_py - sos_r) <= self.DOY_ATOL, (
            f"DER.SOS: Python={sos_py:.1f}, R={sos_r:.1f}"
        )

    def test_DER_POS(self):
        ref = load("pheno_der.csv")
        pos_r = float(ref["DER.POS"].iloc[0])
        pos_py = float(self.row["DER.POS"])
        assert abs(pos_py - pos_r) <= self.DOY_ATOL

    def test_DER_EOS(self):
        ref = load("pheno_der.csv")
        eos_r = float(ref["DER.EOS"].iloc[0])
        eos_py = float(self.row["DER.EOS"])
        assert abs(eos_py - eos_r) <= self.DOY_ATOL

    def test_GU(self):
        ref = load("pheno_gu.csv").iloc[0]
        for name in ("UD", "SD", "DD", "RD"):
            assert abs(float(self.row[name]) - float(ref[name])) <= self.DOY_ATOL

    def test_ZHANG(self):
        ref = load("pheno_zhang.csv").iloc[0]
        for name in ("GreenUp", "Maturity", "Senescence", "Dormancy"):
            py_value = float(self.row[name])
            r_value = float(ref[name])
            if np.isnan(r_value):
                assert np.isnan(py_value)
            else:
                assert abs(py_value - r_value) <= self.DOY_ATOL
